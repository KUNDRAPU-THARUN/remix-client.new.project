/**
 * Returns city-specific category configuration.
 * Prevents Chittoor-exclusive categories (e.g. Kanipakam cabs, mango mandis)
 * from leaking onto Vellore or Bengaluru city directory views.
 */
export function getCityCategories(cityId: CityId): Category[] {
  switch (cityId) {
    case 'vellore':
      return VELLORE_CATEGORIES;
    case 'bengaluru':
      return BENGALURU_CATEGORIES;
    case 'chittoor':
    default:
      return CHITTOOR_CATEGORIES;
  }
}

/**
 * Resolves a category by ID within a city scope.
 */
export function getCityCategory(cityId: CityId, categoryId: string): Category | undefined {
  const categories = getCityCategories(cityId);
  return categories.find((c) => c.id === categoryId);
}
